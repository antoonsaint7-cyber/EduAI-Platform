const ACTIONS = {
  quiz: 'أنشئ اختبارًا من 10 أسئلة متنوعة مع نموذج إجابة في النهاية.',
  review: 'حوّل الأخطاء المذكورة إلى مراجعة قصيرة ثم 5 أسئلة علاجية.',
  plan: 'أنشئ خطة مذاكرة أسبوعية واقعية تتدرج من الفهم إلى التطبيق والمراجعة.',
  explain: 'اشرح المحتوى شرحًا مترابطًا وبسيطًا مع أمثلة.',
};

function buildEducationalPrompt({ mode = 'student', subject = '', level = '', action = '', text = '' }) {
  const student = mode === 'student';
  const rules = student
    ? 'استخدم أسلوبًا سقراطيًا: ابدأ بتلميح ثم سؤال تحقق، ولا تكشف الإجابة النهائية إلا بعد محاولة مناسبة. صحح الخطأ واشرح السبب.'
    : 'استخدم أسلوبًا احترافيًا للمدرس: أهداف تعلم، تمهيد، شرح متدرج، أمثلة، وأسئلة تقويم.';
  return [
    'أنت AI Tutor عربي داخل منصة تعليمية.',
    `الوضع: ${student ? 'طالب' : 'مدرس'}. المادة: ${subject || 'غير محددة'}. المستوى: ${level || 'غير محدد'}.`,
    rules,
    ACTIONS[action] || '',
    'اعتمد على المحتوى الذي يقدمه المستخدم والمصادر المرتبطة به. لا تخترع حقيقة من منهج محدد عند غياب الدليل. إذا كان المصدر غامضًا أو متعارضًا فصرّح بذلك واقترح مراجعة المعلم.',
    `المحتوى/السؤال: ${text}`,
  ].filter(Boolean).join('\n');
}

module.exports = { buildEducationalPrompt };
